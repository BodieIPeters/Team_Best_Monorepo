-- Church Match database schema (Postgres / Supabase).
-- Built from docs/DOMAIN_MODEL.md. Each entity is a table; each relationship is
-- a foreign key, or a join table when it is many-to-many.
-- Column names use snake_case because Postgres ignores capitals in unquoted names.

-- A church. description, rating and distance_miles are shown on every church card.
CREATE TABLE IF NOT EXISTS churches (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            TEXT NOT NULL,
    address         TEXT NOT NULL,
    city            TEXT NOT NULL,
    state           TEXT NOT NULL,
    zip             TEXT NOT NULL,
    denomination    TEXT NOT NULL,
    worship_style   TEXT NOT NULL
        CHECK (worship_style IN ('Contemporary', 'Traditional', 'Liturgical', 'Blended')),
    description     TEXT,
    rating          NUMERIC(2,1) CHECK (rating BETWEEN 0 AND 5),
    distance_miles  NUMERIC(4,1) CHECK (distance_miles >= 0)
);

-- A student. Holds the preferences from the quiz.
CREATE TABLE IF NOT EXISTS users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_address   TEXT NOT NULL UNIQUE,
    name            TEXT,
    denomination    TEXT,
    worship_style   TEXT,
    service_time    TEXT,
    max_distance    NUMERIC(4,1)
);

-- A person who manages a church (a church has one or more).
CREATE TABLE IF NOT EXISTS administrators (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    church_id       BIGINT NOT NULL REFERENCES churches(id) ON DELETE CASCADE,
    email_address   TEXT NOT NULL UNIQUE,
    name            TEXT NOT NULL
);

-- One weekly service (a church has one or more).
CREATE TABLE IF NOT EXISTS services (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    church_id       BIGINT NOT NULL REFERENCES churches(id) ON DELETE CASCADE,
    day_of_week     TEXT NOT NULL
        CHECK (day_of_week IN ('Sunday', 'Monday', 'Tuesday', 'Wednesday',
                               'Thursday', 'Friday', 'Saturday')),
    start_time      TIME NOT NULL
);

-- A group a church runs (zero or more).
CREATE TABLE IF NOT EXISTS ministries (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    church_id       BIGINT NOT NULL REFERENCES churches(id) ON DELETE CASCADE,
    name            TEXT NOT NULL,
    description     TEXT
);

-- An event a church hosts. It may belong to one ministry, or to none.
CREATE TABLE IF NOT EXISTS events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    church_id       BIGINT NOT NULL REFERENCES churches(id) ON DELETE CASCADE,
    ministry_id     BIGINT REFERENCES ministries(id) ON DELETE SET NULL,
    title           TEXT NOT NULL,
    event_time      TIMESTAMPTZ NOT NULL
);

-- Which users attend which events (many users to many events).
CREATE TABLE IF NOT EXISTS event_attendees (
    user_id         BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    event_id        BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, event_id)
);

-- A user's visit to one service. rating and comment are the optional feedback.
CREATE TABLE IF NOT EXISTS visits (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    service_id      BIGINT NOT NULL REFERENCES services(id) ON DELETE CASCADE,
    visit_time      TIMESTAMPTZ NOT NULL,
    rating          INTEGER CHECK (rating BETWEEN 1 AND 5),
    comment         TEXT
);

-- A church suggested to a user, with how well it matched.
CREATE TABLE IF NOT EXISTS suggestions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    church_id       BIGINT NOT NULL REFERENCES churches(id) ON DELETE CASCADE,
    match_score     NUMERIC(3,2) NOT NULL CHECK (match_score BETWEEN 0 AND 1),
    suggested_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Churches a user saved (many users to many churches).
CREATE TABLE IF NOT EXISTS favorites (
    user_id         BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    church_id       BIGINT NOT NULL REFERENCES churches(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, church_id)
);

-- Indexes on foreign keys, so looking up a church's rows stays fast.
CREATE INDEX IF NOT EXISTS idx_administrators_church ON administrators(church_id);
CREATE INDEX IF NOT EXISTS idx_services_church       ON services(church_id);
CREATE INDEX IF NOT EXISTS idx_ministries_church     ON ministries(church_id);
CREATE INDEX IF NOT EXISTS idx_events_church         ON events(church_id);
CREATE INDEX IF NOT EXISTS idx_events_ministry       ON events(ministry_id);
CREATE INDEX IF NOT EXISTS idx_visits_user           ON visits(user_id);
CREATE INDEX IF NOT EXISTS idx_visits_service        ON visits(service_id);
CREATE INDEX IF NOT EXISTS idx_suggestions_user      ON suggestions(user_id);
CREATE INDEX IF NOT EXISTS idx_suggestions_church    ON suggestions(church_id);